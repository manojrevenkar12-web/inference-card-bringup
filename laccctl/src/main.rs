//! laccctl: bring-up and service tool for the LACC inference card.
//!
//!   laccctl status [--json]                    card, firmware, sensors, FRU, counters
//!   laccctl fw inspect <image>                 verify an image the way the boot ROM does
//!   laccctl fw update <image> --slot a|b       write a slot over MTD, set the boot slot, reboot
//!   laccctl trace --seconds N [--workload]     driver tracepoints -> Perfetto JSON
//!   laccctl regs                               decode BAR0 through sysfs resource0
//!   laccctl fault <dma|hang|thermal|link|cqe>  arm a fault through debugfs

mod fw;
mod mtd;
#[rustfmt::skip] // generated by tools/gen_regs.py
mod regs;
mod trace;
mod uapi;

use anyhow::{anyhow, bail, Context, Result};
use clap::{Parser, Subcommand, ValueEnum};
use serde_json::json;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

#[derive(Parser)]
#[command(
    version,
    about = "Bring-up and service tool for the LACC inference card"
)]
struct Cli {
    /// PCI device directory (default: the first 1234:7acc device)
    #[arg(long, global = true)]
    device: Option<PathBuf>,
    #[command(subcommand)]
    cmd: Cmd,
}

#[derive(Subcommand)]
enum Cmd {
    /// Card, firmware, sensors, FRU and counters
    Status {
        #[arg(long)]
        json: bool,
    },
    /// Firmware images
    Fw {
        #[command(subcommand)]
        cmd: FwCmd,
    },
    /// Record the driver's tracepoints as a Perfetto (Chrome JSON) trace
    Trace {
        #[arg(long, default_value_t = 2)]
        seconds: u64,
        /// Run a small mixed workload on /dev/lacc0 while tracing
        #[arg(long)]
        workload: bool,
        #[arg(short, long, default_value = "lacc-trace.json")]
        output: PathBuf,
    },
    /// Read and decode the register file (BAR0)
    Regs,
    /// Arm a fault on the card (needs debugfs)
    Fault { kind: FaultKind },
}

#[derive(Subcommand)]
enum FwCmd {
    /// Verify an image as the boot ROM would and list its records
    Inspect {
        image: PathBuf,
        #[arg(long)]
        json: bool,
    },
    /// Write an image to a slot, point the boot config at it and reboot the card
    Update {
        image: PathBuf,
        #[arg(long)]
        slot: Slot,
        /// Slot to boot afterwards (default: the slot just written)
        #[arg(long)]
        boot_slot: Option<BootSlot>,
        /// Write even if the image fails verification or is below the rollback floor
        /// (for validating the boot ROM; the card will refuse to boot it)
        #[arg(long)]
        force: bool,
        /// Write and configure, but do not reboot the card
        #[arg(long)]
        no_reboot: bool,
    },
}

#[derive(Clone, Copy, ValueEnum, PartialEq, Debug)]
enum Slot {
    A,
    B,
}

#[derive(Clone, Copy, ValueEnum, PartialEq, Debug)]
enum BootSlot {
    A,
    B,
    Newest,
}

#[derive(Clone, Copy, ValueEnum, Debug)]
enum FaultKind {
    Dma,
    Hang,
    Thermal,
    Link,
    Cqe,
}

struct Card {
    pci: PathBuf,
}

impl Card {
    fn find(explicit: Option<PathBuf>) -> Result<Card> {
        if let Some(p) = explicit {
            return Ok(Card { pci: p });
        }
        for e in fs::read_dir("/sys/bus/pci/devices")? {
            let p = e?.path();
            let id = |f: &str| {
                fs::read_to_string(p.join(f))
                    .unwrap_or_default()
                    .trim()
                    .to_string()
            };
            if id("vendor") == format!("{:#06x}", regs::VENDOR_ID)
                && id("device") == format!("{:#06x}", regs::DEVICE_ID)
            {
                return Ok(Card { pci: p });
            }
        }
        bail!("no LACC card (1234:7acc) on the PCI bus")
    }
    fn attr(&self, name: &str) -> Result<String> {
        let p = self.pci.join("lacc").join(name);
        Ok(fs::read_to_string(&p)
            .with_context(|| format!("read {}", p.display()))?
            .trim()
            .to_string())
    }
    fn attr_u64(&self, name: &str) -> Result<u64> {
        parse_num(&self.attr(name)?).ok_or_else(|| anyhow!("{name}: not a number"))
    }
    fn set(&self, name: &str, v: &str) -> Result<()> {
        let p = self.pci.join("lacc").join(name);
        fs::write(&p, v).with_context(|| format!("write {} to {}", v.trim(), p.display()))
    }
    fn bdf(&self) -> String {
        self.pci
            .file_name()
            .map(|s| s.to_string_lossy().into_owned())
            .unwrap_or_default()
    }
}

fn parse_num(s: &str) -> Option<u64> {
    let s = s.trim();
    match s.strip_prefix("0x") {
        Some(h) => u64::from_str_radix(h, 16).ok(),
        None => s.parse().ok(),
    }
}

fn hwmon(name: &str) -> Option<PathBuf> {
    fs::read_dir("/sys/class/hwmon")
        .ok()?
        .flatten()
        .map(|e| e.path())
        .find(|p| {
            fs::read_to_string(p.join("name"))
                .map(|n| n.trim() == name)
                .unwrap_or(false)
        })
}

fn fru() -> Option<(String, bool)> {
    let dev = fs::read_dir("/sys/bus/i2c/devices")
        .ok()?
        .flatten()
        .map(|e| e.path())
        .find(|p| {
            p.file_name()
                .map(|n| n.to_string_lossy().ends_with("-0050"))
                .unwrap_or(false)
        })?;
    let rom = fs::read(dev.join("eeprom")).ok()?;
    let sum = rom.iter().fold(0u8, |a, b| a.wrapping_add(*b));
    let text = rom
        .split(|b| *b == 0)
        .next()
        .map(|t| String::from_utf8_lossy(t).into_owned())?;
    Some((text, sum == 0))
}

fn status(card: &Card, as_json: bool) -> Result<()> {
    let st = card.attr_u64("card_status")? as u32;
    let fws = card.attr_u64("fw_status")? as u32;
    fn flags(v: u32, names: &[(u32, &'static str)]) -> Vec<&'static str> {
        names
            .iter()
            .filter(|(b, _)| v & b != 0)
            .map(|(_, n)| *n)
            .collect()
    }
    let status_flags = flags(
        st,
        &[
            (regs::STATUS_READY, "ready"),
            (regs::STATUS_BUSY, "busy"),
            (regs::STATUS_HALTED, "halted"),
            (regs::STATUS_FW_OK, "firmware-ok"),
            (regs::STATUS_THROTTLED, "throttled"),
            (regs::STATUS_ERROR, "error"),
            (regs::STATUS_RECOVERY, "recovery"),
        ],
    );
    let fw_flags = flags(
        fws,
        &[
            (regs::FW_A_VALID, "a-valid"),
            (regs::FW_B_VALID, "b-valid"),
            (regs::FW_A_ROLLBACK, "a-below-floor"),
            (regs::FW_B_ROLLBACK, "b-below-floor"),
            (regs::FW_LUT_LOADED, "lut-loaded"),
        ],
    );
    let mut sensors = serde_json::Map::new();
    if let Some(h) = hwmon("pmbus") {
        for (k, f, scale) in [
            ("vin_v", "in1_input", 1e3),
            ("vout_v", "in2_input", 1e3),
            ("iout_a", "curr2_input", 1e3),
            ("pout_w", "power2_input", 1e6),
            ("vr_temp_c", "temp1_input", 1e3),
        ] {
            if let Some(v) = fs::read_to_string(h.join(f))
                .ok()
                .and_then(|s| s.trim().parse::<f64>().ok())
            {
                sensors.insert(k.into(), json!(v / scale));
            }
        }
    }
    let stats: serde_json::Map<String, serde_json::Value> = card
        .attr("stats")?
        .lines()
        .filter_map(|l| l.split_once(' '))
        .map(|(k, v)| (k.to_string(), json!(v.parse::<u64>().unwrap_or(0))))
        .collect();
    let (fru_text, fru_ok) = fru().unwrap_or_default();
    let j = json!({
        "pci": card.bdf(),
        "status": status_flags,
        "firmware": {"version": card.attr_u64("fw_version")?, "slot": card.attr("booted_slot")?, "rollback_floor": card.attr_u64("fw_min_version")?, "flags": fw_flags},
        "power": {"board_w": card.attr_u64("power_mw")? as f64 / 1e3, "cap_w": card.attr_u64("power_cap_mw")? as f64 / 1e3,
                  "clock_mhz": card.attr_u64("clock_mhz")?, "die_c": card.attr_u64("temp_mc")? as f64 / 1e3, "energy_j": card.attr_u64("energy_uj")? as f64 / 1e6},
        "regulator": sensors,
        "fru": {"record": fru_text, "checksum_ok": fru_ok},
        "counters": stats,
    });
    if as_json {
        println!("{j}");
    } else {
        println!(
            "LACC card at {}: {}",
            j["pci"].as_str().unwrap_or("?"),
            status_flags.join(", ")
        );
        println!(
            "firmware  {} from slot {} (rollback floor {}; {})",
            j["firmware"]["version"],
            j["firmware"]["slot"].as_str().unwrap_or("?"),
            j["firmware"]["rollback_floor"],
            fw_flags.join(", ")
        );
        println!(
            "power     {:.1} W at {} MHz, die {:.1} C, cap {} W",
            j["power"]["board_w"].as_f64().unwrap_or(0.0),
            j["power"]["clock_mhz"],
            j["power"]["die_c"].as_f64().unwrap_or(0.0),
            j["power"]["cap_w"]
        );
        for (k, v) in &sensors {
            println!("regulator {k:<10} {:.3}", v.as_f64().unwrap_or(0.0));
        }
        println!(
            "FRU       {} ({})",
            fru_text,
            if fru_ok {
                "checksum ok"
            } else {
                "bad checksum"
            }
        );
        for (k, v) in &stats {
            println!("counter   {k:<15} {v}");
        }
    }
    Ok(())
}

fn fw_inspect(path: &Path, as_json: bool) -> Result<bool> {
    let img = fs::read(path).with_context(|| format!("read {}", path.display()))?;
    let r = fw::inspect(&img)?;
    if as_json {
        println!("{}", serde_json::to_string(&r)?);
    } else {
        println!(
            "{}: version {}, rollback index {}, {} bytes of payload",
            path.display(),
            r.header.version,
            r.header.rollback_index,
            r.header.payload_len
        );
        println!(
            "  magic {}  header CRC {}  payload SHA-256 {}  records {}",
            ok(r.magic_ok),
            ok(r.crc_ok),
            ok(r.sha256_ok),
            ok(r.tlvs_ok)
        );
        for t in &r.tlvs {
            println!("  record {} ({}), {} bytes", t.kind, t.name, t.data.len());
        }
        if let Some(b) = &r.build {
            println!("  build \"{b}\"");
        }
    }
    Ok(r.valid())
}

fn ok(b: bool) -> &'static str {
    if b {
        "ok"
    } else {
        "BAD"
    }
}

fn fw_update(
    card: &Card,
    path: &Path,
    slot: Slot,
    boot: Option<BootSlot>,
    force: bool,
    no_reboot: bool,
) -> Result<()> {
    let img = fs::read(path).with_context(|| format!("read {}", path.display()))?;
    if img.len() > fw::SLOT_SIZE {
        bail!(
            "image is {} bytes; a slot holds {}",
            img.len(),
            fw::SLOT_SIZE
        );
    }
    let r = fw::inspect(&img)?;
    let floor = card.attr_u64("fw_min_version")? as u32;
    if !force {
        if let Some(p) = r.problem() {
            bail!("refusing {}: {p}", path.display());
        }
        if r.header.rollback_index < floor {
            bail!(
                "refusing {}: rollback index {} is below the card's floor {floor}",
                path.display(),
                r.header.rollback_index
            );
        }
    }
    let part = mtd::Partition::find(match slot {
        Slot::A => "lacc-fw-a",
        Slot::B => "lacc-fw-b",
    })?;
    let t0 = Instant::now();
    part.erase(0, part.info.size)?;
    part.write_verify(0, &img)?;
    let boot = boot.unwrap_or(match slot {
        Slot::A => BootSlot::A,
        Slot::B => BootSlot::B,
    });
    let cfg_part = mtd::Partition::find("lacc-config")?;
    let old = cfg_part.read(0, 16)?;
    let mirror = fw::parse_config(&old)
        .map(|(_, m)| m)
        .unwrap_or(0)
        .max(floor);
    cfg_part.erase(0, cfg_part.info.erasesize)?;
    cfg_part.write_verify(
        0,
        &fw::config(
            match boot {
                BootSlot::A => 1,
                BootSlot::B => 2,
                BootSlot::Newest => 0,
            },
            mirror,
        ),
    )?;
    let wrote = t0.elapsed();
    if no_reboot {
        println!(
            "wrote version {} to slot {:?} in {:.0} ms; boot slot {:?}; not rebooted",
            r.header.version,
            slot,
            wrote.as_secs_f64() * 1e3,
            boot
        );
        return Ok(());
    }
    let t1 = Instant::now();
    let mut tries = 0;
    loop {
        match card.set("fw_reboot", "1") {
            Ok(()) => break,
            Err(e) if tries < 50 && format!("{e:#}").contains("busy") => {
                tries += 1;
                std::thread::sleep(Duration::from_millis(100));
            }
            Err(e) => return Err(e),
        }
    }
    let deadline = Instant::now() + Duration::from_secs(5);
    while card.attr_u64("card_status")? as u32 & regs::STATUS_READY == 0 {
        if Instant::now() > deadline {
            bail!("card not ready 5 s after the firmware reboot");
        }
        std::thread::sleep(Duration::from_millis(10));
    }
    println!("wrote version {} to slot {:?} in {:.0} ms; card rebooted in {:.0} ms and runs version {} from slot {}",
             r.header.version, slot, wrote.as_secs_f64() * 1e3, t1.elapsed().as_secs_f64() * 1e3,
             card.attr("fw_version")?, card.attr("booted_slot")?);
    Ok(())
}

const TRACEFS: &str = "/sys/kernel/tracing";

fn trace_cmd(seconds: u64, workload: bool, output: &Path) -> Result<()> {
    let w = |f: &str, v: &str| {
        fs::write(Path::new(TRACEFS).join(f), v).with_context(|| format!("tracefs {f}"))
    };
    w("tracing_on", "0")?;
    w("buffer_size_kb", "8192")?;
    w("trace", "")?;
    w("events/lacc/enable", "1")?;
    w("tracing_on", "1")?;
    let deadline = Instant::now() + Duration::from_secs(seconds);
    if workload {
        uapi::workload(deadline)?;
    } else {
        std::thread::sleep(Duration::from_secs(seconds));
    }
    w("tracing_on", "0")?;
    let text = fs::read_to_string(Path::new(TRACEFS).join("trace"))?;
    w("events/lacc/enable", "0")?;
    let events: Vec<_> = text.lines().filter_map(trace::parse_line).collect();
    let (j, s) = trace::to_perfetto(&events);
    fs::write(output, serde_json::to_vec(&j)?)?;
    println!("{} events, {} jobs ({} failed, {} resets); host latency p50 {:.0} us, p99 {:.0} us; wrote {}",
             events.len(), s.jobs, s.failed, s.resets, s.p50_us, s.p99_us, output.display());
    Ok(())
}

fn regs_cmd(card: &Card) -> Result<()> {
    let bar = mtd::Bar0::open(&card.pci.join("resource0"))?;
    for (name, off, access, doc) in regs::REGISTERS {
        if *access == "wo" || name.starts_with("I2C_DATA") || name.starts_with("SPI_") {
            continue; // write-only registers and data windows
        }
        println!(
            "{off:#06x} {name:<20} {:#010x}  {access:<3} {doc}",
            bar.read(*off)
        );
    }
    Ok(())
}

fn fault_cmd(kind: FaultKind) -> Result<()> {
    let bit = match kind {
        FaultKind::Dma => regs::FAULT_DMA_ERROR,
        FaultKind::Hang => regs::FAULT_HANG,
        FaultKind::Thermal => regs::FAULT_THERMAL,
        FaultKind::Link => regs::FAULT_LINK_DOWN,
        FaultKind::Cqe => regs::FAULT_BAD_CQE,
    };
    fs::write("/sys/kernel/debug/lacc0/fault_inject", bit.to_string())
        .context("debugfs fault_inject")?;
    println!("armed {kind:?} ({bit:#x})");
    Ok(())
}

fn main() {
    let cli = Cli::parse();
    let res = (|| -> Result<i32> {
        match cli.cmd {
            Cmd::Status { json } => status(&Card::find(cli.device)?, json).map(|_| 0),
            Cmd::Fw {
                cmd: FwCmd::Inspect { image, json },
            } => fw_inspect(&image, json).map(|v| if v { 0 } else { 2 }),
            Cmd::Fw {
                cmd:
                    FwCmd::Update {
                        image,
                        slot,
                        boot_slot,
                        force,
                        no_reboot,
                    },
            } => fw_update(
                &Card::find(cli.device)?,
                &image,
                slot,
                boot_slot,
                force,
                no_reboot,
            )
            .map(|_| 0),
            Cmd::Trace {
                seconds,
                workload,
                output,
            } => trace_cmd(seconds, workload, &output).map(|_| 0),
            Cmd::Regs => regs_cmd(&Card::find(cli.device)?).map(|_| 0),
            Cmd::Fault { kind } => fault_cmd(kind).map(|_| 0),
        }
    })();
    match res {
        Ok(code) => std::process::exit(code),
        Err(e) => {
            eprintln!("laccctl: {e:#}");
            std::process::exit(1);
        }
    }
}
