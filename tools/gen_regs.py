#!/usr/bin/env python3
"""Generate the register map for C (device model, driver, runtime), Rust (laccctl) and docs
from regs/lacc.yaml. `--check` fails if a generated file is out of date (CI)."""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "regs" / "lacc.yaml"
HEADER = "Generated by tools/gen_regs.py from regs/lacc.yaml. Do not edit."


def load() -> dict:
    return yaml.safe_load(SRC.read_text())


def c_header(m: dict) -> str:
    d = m["device"]
    out = [
        "/* SPDX-License-Identifier: GPL-2.0 OR MIT */",
        f"/* {HEADER} */",
        "#ifndef LACC_REGS_H",
        "#define LACC_REGS_H",
        "",
    ]
    for k, v in d.items():
        if k == "name":
            continue
        out.append(f"#define LACC_{k.upper():<28} 0x{v:X}u" if isinstance(v, int) else f"#define LACC_{k.upper()} {v}")
    out.append("")
    for r in m["registers"]:
        out.append(f"#define LACC_REG_{r['name']:<24} 0x{r['offset']:04X}u  /* {r['access']}: {r['doc']} */")
    out.append("")
    for group, bits in m["bits"].items():
        for name, bit in bits.items():
            out.append(f"#define LACC_{group}_{name:<20} (1u << {bit})")
        out.append("")
    for name, v in m["values"].items():
        if isinstance(v, dict):
            for k, x in v.items():
                out.append(f"#define LACC_{name}_{k:<20} {x}u")
        else:
            out.append(f"#define LACC_{name:<24} 0x{v:X}u")
        out.append("")
    out += ["#endif /* LACC_REGS_H */", ""]
    return "\n".join(out)


def rust(m: dict) -> str:
    out = [f"// {HEADER}", "#![allow(dead_code)]", ""]
    for k, v in m["device"].items():
        if isinstance(v, int):
            out.append(f"pub const {k.upper()}: u64 = 0x{v:X};")
    out.append("")
    for r in m["registers"]:
        out.append(f"/// {r['doc']}")
        out.append(f"pub const REG_{r['name']}: u64 = 0x{r['offset']:04X};")
    out.append("")
    out.append("/// Every register: name, offset, access, description.")
    out.append("pub const REGISTERS: &[(&str, u64, &str, &str)] = &[")
    for r in m["registers"]:
        doc = r["doc"].replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    ("{r["name"]}", 0x{r["offset"]:04X}, "{r["access"]}", "{doc}"),')
    out.append("];")
    out.append("")
    for group, bits in m["bits"].items():
        for name, bit in bits.items():
            out.append(f"pub const {group}_{name}: u32 = 1 << {bit};")
    for name, v in m["values"].items():
        if isinstance(v, dict):
            for k, x in v.items():
                out.append(f"pub const {name}_{k}: u32 = {x};")
        else:
            out.append(f"pub const {name}: u32 = 0x{v:X};")
    out.append("")
    return "\n".join(out)


def markdown(m: dict) -> str:
    d = m["device"]
    out = [
        "# Register map",
        "",
        f"_{HEADER}_",
        "",
        (
            f"PCI ID `{d['vendor_id']:04x}:{d['device_id']:04x}`, class `{d['class']:04x}` (processing accelerator). "
            f"BAR0: {d['bar0_size'] // 1024} KiB of registers. BAR2: {d['bar2_size'] // 2**20} MiB of device memory. "
            f"{d['msix_vectors']} MSI-X vectors. JTAG IDCODE `0x{d['jtag_idcode']:08X}`."
        ),
        "",
        "| Offset | Name | Access | Description |",
        "|---|---|---|---|",
    ]
    for r in m["registers"]:
        out.append(f"| `0x{r['offset']:04X}` | `{r['name']}` | {r['access']} | {r['doc']} |")
    out += ["", "## Bits", ""]
    for group, bits in m["bits"].items():
        out.append(f"- **{group}**: " + ", ".join(f"`{k}` = bit {v}" for k, v in bits.items()))
    out += ["", "## Values", ""]
    for name, v in m["values"].items():
        if isinstance(v, dict):
            out.append(f"- **{name}**: " + ", ".join(f"`{k}` = {x}" for k, x in v.items()))
        else:
            out.append(f"- **{name}**: `0x{v:X}`")
    out.append("")
    return "\n".join(out)


TARGETS = {
    "include/lacc_regs.h": c_header,
    "laccctl/src/regs.rs": rust,
    "docs/REGISTERS.md": markdown,
}


def main() -> int:
    m = load()
    stale = []
    for rel, fn in TARGETS.items():
        p = ROOT / rel
        text = fn(m)
        if "--check" in sys.argv:
            if not p.exists() or p.read_text() != text:
                stale.append(rel)
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    if stale:
        print("out of date (run tools/gen_regs.py):", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
